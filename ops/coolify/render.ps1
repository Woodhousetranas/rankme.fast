#requires -Version 7.0
[CmdletBinding()]
param([switch]$Check)
$ErrorActionPreference = 'Stop'
$root = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot '../..'))
$target = Join-Path $root 'docker-compose.coolify.rendered.yml'
# Never resolve a private .env into the checked-in deployment definition.
$lines = & docker compose --project-directory $root --env-file (Join-Path $root '.env.example') -f (Join-Path $root 'docker-compose.yml') -f (Join-Path $root 'docker-compose.coolify.yml') config --no-interpolate --no-path-resolution --no-env-resolution
if ($LASTEXITCODE -ne 0) { throw 'Compose render failed.' }
$content = "# Generated by ops/coolify/render.ps1. Use Coolify Raw Compose mode.`n" + 'name: ${COOLIFY_RESOURCE_UUID:?The Coolify application identity is required}' + "`n" + (($lines | Where-Object { $_ -notmatch '^name:' -and $_ -notmatch '^\s+name: rankme-coolify_' }) -join "`n") + "`n"
if ($content -match '(?m)^\s+ports:') { throw 'A Coolify service must not publish host ports.' }
if ($Check) {
    if (-not (Test-Path -LiteralPath $target) -or [IO.File]::ReadAllText($target).Replace("`r`n", "`n") -cne $content) { throw 'Rendered Coolify definition is stale.' }
    Write-Output 'Rendered Coolify definition matches source; no host ports.'
} else { [IO.File]::WriteAllText($target, $content, [Text.UTF8Encoding]::new($false)) }
